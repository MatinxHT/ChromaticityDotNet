"""Generate synthetic textile examples from archived CIE tables (Python standard library only).

The 10 nm sample is interpolated to 1 nm before integration, matching REFToXYZ.
A smooth perturbation is approximately balanced under D65 / CIE 1964 10 degrees,
retaining a small mismatch before quantizing reflectances to two decimal places.
These demonstration spectra are synthetic, not measured fabric reference data.
"""
import csv
import math
from decimal import Decimal, ROUND_HALF_EVEN
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WAVELENGTHS = list(range(380, 781, 10))


def table(path):
    with (ROOT / path).open(encoding="utf-8-sig", newline="") as stream:
        return {int(row[0]): [float(value) for value in row[1:]] for row in csv.reader(stream) if row}


def interpolate(values, wavelength):
    offset = (wavelength - 380) / 10
    index = min(int(offset), len(values) - 2)
    return values[index] + (values[index + 1] - values[index]) * (offset - index)


def solve(matrix, vector):
    rows = [list(row) + [value] for row, value in zip(matrix, vector)]
    for column in range(len(rows)):
        pivot = max(range(column, len(rows)), key=lambda index: abs(rows[index][column]))
        rows[column], rows[pivot] = rows[pivot], rows[column]
        scale = rows[column][column]
        rows[column] = [value / scale for value in rows[column]]
        for index in range(len(rows)):
            if index != column:
                scale = rows[index][column]
                rows[index] = [a - scale * b for a, b in zip(rows[index], rows[column])]
    return [row[-1] for row in rows]


def main():
    observer = table("reference/observers/CIE_xyz_1964_10deg.csv")
    # Match the library's documented treatment of the CIE 1964 z-bar undefined tail.
    for wavelength, values in observer.items():
        if wavelength >= 560 and math.isnan(values[2]):
            values[2] = 0
    d65 = table("reference/illuminants/CIE_std_illum_D65.csv")

    def xyz(values):
        return [sum(interpolate(values, wavelength) * d65[wavelength][0] * observer[wavelength][axis]
                    for wavelength in range(380, 781)) for axis in range(3)]

    basis = [[math.exp(-0.5 * ((wavelength - center) / 30) ** 2) for wavelength in WAVELENGTHS]
             for center in (445, 540, 610)]
    seed = [math.sin((wavelength - 380) * math.pi / 90) for wavelength in WAVELENGTHS]
    coefficients = solve(list(zip(*(xyz(values) for values in basis))), xyz(seed))
    # Leave a small residual instead of forcing identical tristimulus values.
    residual = [value - 0.995 * sum(coefficient * values[index] for coefficient, values in zip(coefficients, basis))
                for index, value in enumerate(seed)]
    scale = 18 / max(abs(value) for value in residual)
    def percent(value):
        return Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_EVEN)

    standard = [percent(41.5 - 23.5 * math.cos(math.pi * index / 20)) for index in range(41)]
    sample = [percent(float(value) + scale * residual[index]) for index, value in enumerate(standard)]
    different = [percent(value * Decimal("0.65")) for value in standard]
    assert all(0 <= value <= 100 for value in sample)
    assets = ROOT / "apps/Chromaticity.Tools.Browser/wwwroot/examples/metamerism"
    assets.mkdir(parents=True, exist_ok=True)
    for name, values in (("standard", standard), ("metameric-sample", sample), ("different-sample", different)):
        for fraction in (False, True):
            suffix = "-fraction" if fraction else ""
            with (assets / f"{name}{suffix}.csv").open("w", encoding="utf-8", newline="") as stream:
                writer = csv.writer(stream)
                writer.writerow(["wavelength_nm", "reflectance_fraction" if fraction else "reflectance_percent"])
                writer.writerows((wavelength, format(value / (100 if fraction else 1), ".4f" if fraction else ".2f"))
                                 for wavelength, value in zip(WAVELENGTHS, values))
    source = '''// Generated by tools/generate_textile_metamerism_examples.py; synthetic demonstration data.
namespace Chromaticity.Tools.Services;

public static class TextileMetamerismExamples
{
    public const string Notice = "示例为合成相对反射光谱，380–780 nm / 10 nm；同色异谱示例在 D65 / 10° 下近似同色，换光源后色差增大。切换观察者可能改变配色情况。";
    public static string Standard => GetStandard();
    public static string MetamericSample => GetMetamericSample();
    public static string DifferentSample => GetDifferentSample();
    public static string GetStandard(bool fraction = false) => ReflectanceExamples.Format(StandardValues, 380, 10, fraction);
    public static string GetMetamericSample(bool fraction = false) => ReflectanceExamples.Format(SampleValues, 380, 10, fraction);
    public static string GetDifferentSample(bool fraction = false) => ReflectanceExamples.Format(DifferentValues, 380, 10, fraction);
    private static readonly double[] StandardValues = [STANDARD];
    private static readonly double[] SampleValues = [SAMPLE];
    private static readonly double[] DifferentValues = [DIFFERENT];
}
'''
    source = source.replace("[STANDARD]", "[" + ", ".join(map(str, standard)) + "]")
    source = source.replace("[SAMPLE]", "[" + ", ".join(map(str, sample)) + "]")
    source = source.replace("[DIFFERENT]", "[" + ", ".join(map(str, different)) + "]")
    (ROOT / "apps/Chromaticity.Tools/Services/TextileMetamerismExamples.cs").write_text(source, encoding="utf-8")
    print("Generated standard, metameric and different spectra in percent/fraction units, plus C# examples.")


if __name__ == "__main__":
    main()
